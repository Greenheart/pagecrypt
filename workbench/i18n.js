let locale = 'en'
try {
    if (localStorage.getItem('pagecrypt-language') === 'zh-CN') locale = 'zh-CN'
} catch {
    /* Language selection also works when browser storage is unavailable. */
}

export function t(key, values = {}) {
    const template = messages[locale][key] ?? messages.en.operationFailed
    return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ''))
}

export function localize(element, key, values = {}) {
    element.dataset.i18n = key
    element.dataset.i18nValues = JSON.stringify(values)
    element.textContent = t(key, values)
}

export function setLanguage(value) {
    locale = value === 'zh-CN' ? 'zh-CN' : 'en'
    try {
        localStorage.setItem('pagecrypt-language', locale)
    } catch {
        /* Optional preference. */
    }
    renderLanguage()
}

export function renderLanguage() {
    document.documentElement.lang = locale
    document.title = t('title')
    document.getElementById('language').value = locale
    for (const element of document.querySelectorAll('[data-i18n]')) {
        element.textContent = t(
            element.dataset.i18n,
            JSON.parse(element.dataset.i18nValues || '{}'),
        )
    }
    for (const element of document.querySelectorAll('[data-i18n-label]')) {
        element.setAttribute('aria-label', t(element.dataset.i18nLabel))
    }
    for (const element of document.querySelectorAll('[data-i18n-placeholder]')) {
        element.setAttribute('placeholder', t(element.dataset.i18nPlaceholder))
    }
}
